-- 新增文档类型表（单表存储）
CREATE TABLE document_types (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(500),
    created_at TIMESTAMP(6) NOT NULL
);

CREATE UNIQUE INDEX idx_document_type_name ON document_types (name);

-- 知识库（文档）关联文档类型
ALTER TABLE knowledge_bases ADD COLUMN document_type_id BIGINT;

ALTER TABLE knowledge_bases ADD CONSTRAINT fk_kb_document_type
    FOREIGN KEY (document_type_id) REFERENCES document_types (id);

CREATE INDEX idx_kb_document_type ON knowledge_bases (document_type_id);
